/** Sentences added for modifiers in an exercise's name. */
const MODIFIERS: Array<[RegExp, (m: RegExpExecArray) => string]> = [
  [/\bWeighted\b/, () => ' Hold a dumbbell or kettlebell to add resistance.'],
  [/\bHeavier\b/, () => ' Use a heavier weight than in earlier weeks while keeping smooth control.'],
  [/\bHeavy\b/, () => ' Use a challenging weight that still lets you keep good form.'],
  [/\b(\d)-sec\b/, (m) => ` Take ${m[1]} seconds to lower (the eccentric phase), then return at a normal pace.`],
]
const ECCENTRIC_ONLY = ' Lower slowly with control (about 4 seconds), then return at a normal pace.'

/**
 * Finds a description for `name`: an exact match first, then the base exercise
 * with its modifiers (Weighted, Heavier, N-sec, Eccentric) removed and explained.
 * Returns an empty string when nothing matches.
 */
export function describe(name: string, known: Record<string, string> = {}): string {
  const direct = known[name] ?? DESCRIPTIONS[name]
  if (direct) return direct

  let base = name
  let notes = ''
  for (const [re, sentence] of MODIFIERS) {
    const m = re.exec(base)
    if (m) {
      notes += sentence(m)
      base = base.replace(re, '')
    }
  }
  const hadEccentric = /\bEccentric\b/.test(base)
  base = base.replace(/\bEccentric\b/g, '').replace(/\s+/g, ' ').trim()
  if (hadEccentric && !/Take \d seconds/.test(notes)) notes += ECCENTRIC_ONLY

  const found = known[base] ?? DESCRIPTIONS[base]
  return found ? found + notes : ''
}
